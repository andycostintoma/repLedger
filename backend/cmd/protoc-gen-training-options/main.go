package main

import (
	"flag"
	"fmt"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/encoding/protowire"
	"google.golang.org/protobuf/types/descriptorpb"
)

const (
	stringValField      protowire.Number = 50001
	friendlyStringField protowire.Number = 50002
)

func main() {
	var flags flag.FlagSet
	lang := flags.String("lang", "go", "generated helper language: go or ts")
	protogen.Options{ParamFunc: flags.Set}.Run(func(p *protogen.Plugin) error {
		p.SupportedFeatures = uint64(1)
		for _, file := range p.Files {
			if !file.Generate || len(file.Enums) == 0 {
				continue
			}
			switch *lang {
			case "go":
				generateGo(p, file)
			case "ts":
				generateTS(p, file)
			default:
				return fmt.Errorf("unsupported lang %q", *lang)
			}
		}
		return nil
	})
}

func generateGo(p *protogen.Plugin, file *protogen.File) {
	enums := enumsWithStringValues(file.Enums)
	if len(enums) == 0 {
		return
	}
	g := p.NewGeneratedFile(file.GeneratedFilenamePrefix+".z.options.pb.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-training-options. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	g.P("import \"database/sql\"")
	g.P()
	for _, enum := range enums {
		generateGoEnum(g, enum)
		g.P()
	}
}

func generateGoEnum(g *protogen.GeneratedFile, enum *protogen.Enum) {
	name := enum.GoIdent.GoName
	g.P("var ", stringValMapName(name), " = map[", name, "]string{")
	for _, value := range enum.Values {
		stringVal, _ := enumValueOptions(value)
		g.P(value.GoIdent.GoName, ": ", fmt.Sprintf("%q", stringVal), ",")
	}
	g.P("}")
	g.P()
	g.P("var ", reverseStringValMapName(name), " = map[string]", name, "{")
	for _, value := range enum.Values {
		stringVal, _ := enumValueOptions(value)
		if stringVal == "" {
			continue
		}
		g.P(fmt.Sprintf("%q", stringVal), ": ", value.GoIdent.GoName, ",")
	}
	g.P("}")
	g.P()
	g.P("var ", friendlyStringMapName(name), " = map[", name, "]string{")
	for _, value := range enum.Values {
		_, friendlyString := enumValueOptions(value)
		g.P(value.GoIdent.GoName, ": ", fmt.Sprintf("%q", friendlyString), ",")
	}
	g.P("}")
	g.P()
	g.P("func (x ", name, ") StringVal() string {")
	g.P("return ", stringValMapName(name), "[x]")
	g.P("}")
	g.P()
	g.P("func (x ", name, ") NullStringVal() sql.NullString {")
	g.P("s := x.StringVal()")
	g.P("return sql.NullString{String: s, Valid: s != \"\"}")
	g.P("}")
	g.P()
	g.P("func (x ", name, ") IsUnspecified() bool {")
	g.P("return x == 0")
	g.P("}")
	g.P()
	g.P("func (x ", name, ") FriendlyString() string {")
	g.P("friendlyString := ", friendlyStringMapName(name), "[x]")
	g.P("if friendlyString == \"\" {")
	g.P("return x.String()")
	g.P("}")
	g.P("return friendlyString")
	g.P("}")
	g.P()
	g.P("func StringTo", name, "(x string) ", name, " {")
	g.P("return ", reverseStringValMapName(name), "[x]")
	g.P("}")
	g.P()
	g.P("func NullStringTo", name, "(x sql.NullString) ", name, " {")
	g.P("if !x.Valid {")
	g.P("return 0")
	g.P("}")
	g.P("return StringTo", name, "(x.String)")
	g.P("}")
}

func generateTS(p *protogen.Plugin, file *protogen.File) {
	enums := enumsWithStringValues(file.Enums)
	if len(enums) == 0 {
		return
	}
	path := strings.TrimSuffix(file.Desc.Path(), ".proto") + ".z.options.ts"
	g := p.NewGeneratedFile(path, "")
	g.P("// Code generated by protoc-gen-training-options. DO NOT EDIT.")
	g.P()
	imports := make([]string, 0, len(enums))
	for _, enum := range enums {
		imports = append(imports, enum.GoIdent.GoName)
	}
	sort.Strings(imports)
	g.P("import {", strings.Join(imports, ", "), "} from './", tsGeneratedModuleName(file), "';")
	g.P()
	for _, enum := range enums {
		generateTSEnum(g, enum)
		g.P()
	}
}

func generateTSEnum(g *protogen.GeneratedFile, enum *protogen.Enum) {
	name := enum.GoIdent.GoName
	g.P("export const ", lowerFirst(name), "StringValMap: Partial<Record<", name, ", string>> = {")
	for _, value := range enum.Values {
		stringVal, _ := enumValueOptions(value)
		g.P("[", name, ".", tsEnumValueName(value), "]: ", fmt.Sprintf("%q", stringVal), ",")
	}
	g.P("};")
	g.P()
	g.P("export const ", lowerFirst(name), "FriendlyStringMap: Partial<Record<", name, ", string>> = {")
	for _, value := range enum.Values {
		_, friendlyString := enumValueOptions(value)
		g.P("[", name, ".", tsEnumValueName(value), "]: ", fmt.Sprintf("%q", friendlyString), ",")
	}
	g.P("};")
	g.P()
	g.P("const ", lowerFirst(name), "ReverseStringValMap: Record<string, ", name, "> = {")
	for _, value := range enum.Values {
		stringVal, _ := enumValueOptions(value)
		if stringVal == "" {
			continue
		}
		g.P(fmt.Sprintf("%q", stringVal), ": ", name, ".", tsEnumValueName(value), ",")
	}
	g.P("};")
	g.P()
	g.P("export const ", lowerFirst(name), "StringVal = (value: ", name, "): string => ", lowerFirst(name), "StringValMap[value] ?? '';")
	g.P("export const ", lowerFirst(name), "FriendlyString = (value: ", name, "): string => ", lowerFirst(name), "FriendlyStringMap[value] ?? ", lowerFirst(name), "StringVal(value);")
	g.P("export const stringTo", name, " = (value: string): ", name, " => ", lowerFirst(name), "ReverseStringValMap[value] ?? ", name, ".", tsEnumValueName(enum.Values[0]), ";")
}

func enumsWithStringValues(enums []*protogen.Enum) []*protogen.Enum {
	items := make([]*protogen.Enum, 0, len(enums))
	for _, enum := range enums {
		for _, value := range enum.Values {
			stringVal, friendlyString := enumValueOptions(value)
			if stringVal != "" || friendlyString != "" {
				items = append(items, enum)
				break
			}
		}
	}
	return items
}

func enumValueOptions(value *protogen.EnumValue) (string, string) {
	opts, ok := value.Desc.Options().(*descriptorpb.EnumValueOptions)
	if !ok || opts == nil {
		return "", ""
	}
	unknown := opts.ProtoReflect().GetUnknown()
	var stringVal, friendlyString string
	for len(unknown) > 0 {
		number, typ, n := protowire.ConsumeTag(unknown)
		if n < 0 {
			break
		}
		unknown = unknown[n:]
		var value string
		switch typ {
		case protowire.BytesType:
			bytes, n := protowire.ConsumeBytes(unknown)
			if n < 0 {
				return stringVal, friendlyString
			}
			value = string(bytes)
			unknown = unknown[n:]
		default:
			n := protowire.ConsumeFieldValue(number, typ, unknown)
			if n < 0 {
				return stringVal, friendlyString
			}
			unknown = unknown[n:]
			continue
		}
		switch number {
		case stringValField:
			stringVal = value
		case friendlyStringField:
			friendlyString = value
		}
	}
	return stringVal, friendlyString
}

func stringValMapName(name string) string {
	return "_" + name + "_StringValMap"
}

func reverseStringValMapName(name string) string {
	return "_" + name + "_ReverseStringValMap"
}

func friendlyStringMapName(name string) string {
	return "_" + name + "_FriendlyStringMap"
}

func lowerFirst(value string) string {
	if value == "" {
		return value
	}
	return strings.ToLower(value[:1]) + value[1:]
}

func tsEnumValueName(value *protogen.EnumValue) string {
	return string(value.Desc.Name())
}

func tsGeneratedModuleName(file *protogen.File) string {
	path := strings.TrimSuffix(file.Desc.Path(), ".proto")
	lastSlash := strings.LastIndex(path, "/")
	if lastSlash == -1 {
		return path
	}
	return path[lastSlash+1:]
}
